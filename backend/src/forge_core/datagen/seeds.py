"""32 个专家领域的模板库（槽位化）。

与原 ``build_pristine_dataset.py`` 的区别：这里每条 prompt/response 都由
**带捆绑取值的槽位**渲染而来，不同槽位组合 -> 不同语义内容，
因此 200 条/领域的唯一率可以做到接近 100%（原实现是 156x 重复）。

书写约定
--------
* 槽位占位符用 ``{{name}}``（双花括号），正文里的 LaTeX 单花括号安全。
* **语义内容（题面 + 解答）必须放在行槽位 ``case`` 里**：
  一行就是一个完整的问答配对，从结构上杜绝"问 A 答 B"。
* **修饰语**（语言标注、称呼、附加要求）放风味槽位，
  用 ``decorative=True`` 声明，表示它可以只出现在模板一侧。
* 领域无关的多样性（礼貌前缀、请求后缀、代码围栏、数学分隔符、标点风格）
  由 :mod:`forge_core.datagen.perturb` 统一叠加，模板里不要重复造轮子。
"""

from __future__ import annotations

from .perturb import ROW_SLOT, Slot, SlotValue, Template

# ---------------------------------------------------------------------------
# 简写
# ---------------------------------------------------------------------------


def sv(p, r=None, *rest: str) -> SlotValue:
    """构造一个槽位取值。

    * ``p`` 为 str  -> 填入本槽位自身的名字；为 dict -> 一次填入多个占位符名。
    * ``r`` 为 None -> response 侧沿用 prompt 侧文本。
    * ``*rest``     -> response 侧由多段拼成（用空行分隔）。
    """
    if isinstance(r, dict) and not rest:
        return SlotValue(prompt=p, response=r)
    if r is None and not rest:
        return SlotValue(prompt=p, response=p)
    tail = "\n\n".join(x for x in (r, *rest) if x)
    return SlotValue(prompt=p, response=tail)


def FENCE(prompt: str, lang: str, code: str, *, tail: str = "") -> SlotValue:
    """题面为 ``prompt``，解答为带语言标注的围栏代码块（可选追加 ``tail``）。

    语言标注与代码**必须成对给出**——写成两个独立槽位就会出现
    "用 Go 实现"配 ```python 代码块 这种语义错配。
    """
    resp = f"```{lang}\n{code.rstrip()}\n```"
    if tail:
        resp += "\n\n" + tail
    return SlotValue(prompt=prompt, response=resp)


def RS(prompt: str, lang: str, code: str, note: str) -> SlotValue:
    """:func:`FENCE` 加上"思路/说明"尾注。"""
    return FENCE(prompt, lang, code, tail=note)


def T(domain: str, prompt: str, response: str, slots: list[Slot] | None = None,
      weight: float = 1.0, tags: tuple[str, ...] = ()) -> Template:
    """声明一个模板。``slots`` 里最多有一个行槽位（名为 ``case``）。"""
    return Template(domain=domain, prompt=prompt, response=response,
                    slots=tuple(slots or ()), weight=weight, tags=tags)


def sl(name: str, values: list[SlotValue], weight: float = 1.0,
       decorative: bool = False) -> Slot:
    """声明一个风味槽位。

    ``decorative=True`` 表示只提供修饰语（语言标注、称呼、附加要求），
    允许只出现在模板一侧；否则必须两侧同名出现。
    """
    return Slot(name=name, values=tuple(values), weight=weight,
                decorative=decorative)


